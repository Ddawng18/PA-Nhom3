namespace Linea.Api.Services;

// Reuse the existing image signature/size validation, with a separate private
// bucket so teacher portfolio paths cannot be reused as learner submissions.
public sealed class AssignmentStorage
{
    public IPortfolioStorage Files { get; }
    private readonly IConfiguration config;
    private readonly IHttpClientFactory clients;
    private readonly ILogger<AssignmentStorage> logger;

    public AssignmentStorage(IServiceProvider services, IConfiguration configuration, IWebHostEnvironment environment)
    {
        config = new ConfigurationBuilder().AddConfiguration(configuration)
            .AddInMemoryCollection(new Dictionary<string, string?> {
                ["SUPABASE_STORAGE_BUCKET"] = "assignment-submissions",
                ["TEACHER_DOCS_PATH"] = Path.Combine(environment.ContentRootPath, "App_Data", "assignment-submissions")
            }).Build();
        clients = services.GetRequiredService<IHttpClientFactory>();
        logger = services.GetRequiredService<ILogger<AssignmentStorage>>();
        if (!string.IsNullOrWhiteSpace(config["SUPABASE_URL"]) && !string.IsNullOrWhiteSpace(config["SUPABASE_SERVICE_ROLE_KEY"]))
            Files = ActivatorUtilities.CreateInstance<SupabasePortfolioStorage>(services, config);
        else if (environment.IsDevelopment() && configuration["AUTH_MODE"] == "legacy")
            Files = ActivatorUtilities.CreateInstance<LocalPortfolioStorage>(services, config);
        else throw new InvalidOperationException("Configure SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY for assignment storage.");
    }

    public async Task DeleteReplacedAsync(string? path)
    {
        if (string.IsNullOrWhiteSpace(path)) return;
        // Only paths generated by the upload service are accepted here.
        try
        {
            using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(15));
            if (Files is SupabasePortfolioStorage)
            {
                if (!System.Text.RegularExpressions.Regex.IsMatch(path, @"\A[0-9a-f]{32}\.(jpg|png|webp)\z")) return;
                using var client = clients.CreateClient("supabase-storage");
                using var request = new HttpRequestMessage(HttpMethod.Delete,
                    $"{config["SUPABASE_URL"]!.TrimEnd('/')}/storage/v1/object/assignment-submissions");
                request.Content = System.Net.Http.Json.JsonContent.Create(new { prefixes = new[] { path } });
                request.Headers.TryAddWithoutValidation("apikey", config["SUPABASE_SERVICE_ROLE_KEY"]);
                request.Headers.Authorization = new System.Net.Http.Headers.AuthenticationHeaderValue("Bearer", config["SUPABASE_SERVICE_ROLE_KEY"]);
                using var response = await client.SendAsync(request, timeout.Token);
                if (!response.IsSuccessStatusCode) logger.LogWarning("Could not clean up a replaced assignment image; storage status {Status}", response.StatusCode);
            }
            else if ((await Files.OpenAsync(path, timeout.Token))?.LocalPath is { } local)
                File.Delete(local);
        }
        catch (Exception e) when (e is HttpRequestException or OperationCanceledException or IOException or UnauthorizedAccessException)
        {
            logger.LogWarning("Assignment image cleanup deferred: {FailureType}", e.GetType().Name);
        }
    }
}
