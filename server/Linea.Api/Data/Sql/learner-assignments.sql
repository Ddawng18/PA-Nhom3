-- Run through EF migration AddAssignmentsAndGrades, or manually in Supabase SQL
-- Editor before deploying the matching backend/frontend. No sample users/data.
create table if not exists public.bai_tap (
  ma_bai_tap bigint generated by default as identity primary key,
  ma_bai_hoc bigint not null references public.bai_hoc(ma_bai_hoc),
  de_bai text not null check (btrim(de_bai) <> ''),
  han_nop timestamptz,
  bat_buoc boolean not null default true
);
create table if not exists public.bai_nop (
  ma_bai_nop bigint generated by default as identity primary key,
  ma_bai_tap bigint not null references public.bai_tap(ma_bai_tap),
  ma_nguoi_dung uuid not null references public.nguoi_dung(id),
  duong_dan_anh varchar(500) not null check (btrim(duong_dan_anh) <> ''),
  trang_thai varchar(20) not null default 'CHO_CHAM' check (trang_thai in ('CHO_CHAM', 'DA_CHAM')),
  ngay_nop timestamptz not null default now(),
  ngay_cap_nhat timestamptz not null default now(),
  unique (ma_bai_tap, ma_nguoi_dung)
);
create table if not exists public.ket_qua_cham (
  ma_ket_qua bigint generated by default as identity primary key,
  ma_bai_nop bigint not null unique references public.bai_nop(ma_bai_nop),
  ma_nguoi_cham uuid not null references public.nguoi_dung(id),
  diem numeric(4,2) not null check (diem between 0 and 10),
  nhan_xet text not null check (btrim(nhan_xet) <> ''),
  ngay_cham timestamptz not null default now()
);
create index if not exists ix_assignment_lesson on public.bai_tap(ma_bai_hoc);
create index if not exists ix_submission_student on public.bai_nop(ma_nguoi_dung);
create index if not exists ix_grade_grader on public.ket_qua_cham(ma_nguoi_cham);

alter table public.bai_tap enable row level security;
alter table public.bai_nop enable row level security;
alter table public.ket_qua_cham enable row level security;
alter table public.ghi_danh enable row level security;
alter table public.tien_do_bai_hoc enable row level security;

-- Browser writes must go through authenticated backend endpoints, which check
-- published courses, enrollment, deadlines, ownership and transaction versions.
-- Keep existing own-row SELECT policies for the old dashboard's read access.
revoke all on public.bai_tap, public.bai_nop, public.ket_qua_cham from public;
revoke insert, update, delete on public.ghi_danh, public.tien_do_bai_hoc from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.bai_tap, public.bai_nop, public.ket_qua_cham from anon;
    revoke insert, update, delete on public.ghi_danh, public.tien_do_bai_hoc from anon;
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on public.bai_tap, public.bai_nop, public.ket_qua_cham from authenticated;
    revoke insert, update, delete on public.ghi_danh, public.tien_do_bai_hoc from authenticated;
  end if;
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('assignment-submissions', 'assignment-submissions', false, 10485760,
      array['image/jpeg','image/png','image/webp'])
    on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
    -- A restrictive rule also prevents any existing broad Storage policy from
    -- exposing this bucket. The backend's service role bypasses Storage RLS.
    drop policy if exists assignment_files_backend_only on storage.objects;
    create policy assignment_files_backend_only on storage.objects as restrictive
      for all to anon, authenticated
      using (bucket_id <> 'assignment-submissions')
      with check (bucket_id <> 'assignment-submissions');
  end if;
end;
$$;

-- Reconcile legacy completion flags using the same rule as the backend:
-- all required lessons completed AND all required assignments graded.
with completion as (
  select e.ma_nguoi_dung, e.ma_khoa_hoc,
    exists (select 1 from public.bai_hoc l join public.chuong c using (ma_chuong)
            where c.ma_khoa_hoc = e.ma_khoa_hoc and l.bat_buoc)
    and not exists (
      select 1 from public.bai_hoc l join public.chuong c using (ma_chuong)
      where c.ma_khoa_hoc = e.ma_khoa_hoc and l.bat_buoc and not exists (
        select 1 from public.tien_do_bai_hoc p where p.ma_bai_hoc = l.ma_bai_hoc
          and p.ma_nguoi_dung = e.ma_nguoi_dung and p.trang_thai = 'DA_HOAN_THANH'))
    and not exists (
      select 1 from public.bai_tap a join public.bai_hoc l using (ma_bai_hoc)
      join public.chuong c using (ma_chuong)
      where c.ma_khoa_hoc = e.ma_khoa_hoc and a.bat_buoc and not exists (
        select 1 from public.bai_nop s join public.ket_qua_cham g using (ma_bai_nop)
        where s.ma_bai_tap = a.ma_bai_tap and s.ma_nguoi_dung = e.ma_nguoi_dung and s.trang_thai = 'DA_CHAM')) as complete
  from public.ghi_danh e where e.trang_thai <> 'DA_HUY'
)
update public.ghi_danh e set trang_thai = case when c.complete then 'HOAN_THANH' else 'DANG_HOC' end,
  ngay_hoan_thanh = case when c.complete then coalesce(e.ngay_hoan_thanh, now()) else null end
from completion c where e.ma_nguoi_dung = c.ma_nguoi_dung and e.ma_khoa_hoc = c.ma_khoa_hoc;
