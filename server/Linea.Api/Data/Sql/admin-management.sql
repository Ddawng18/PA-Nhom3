-- D09: the browser still reads the dashboard directly from Supabase. Tighten
-- those read policies so a locked account cannot bypass the backend, and so a
-- lesson read also requires a visible course plus an active enrollment.
-- Security-definer helper avoids recursive RLS evaluation on nguoi_dung.
create or replace function public.linea_account_is_locked()
returns boolean
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select coalesce(
    (select n.is_locked from public.nguoi_dung n where n.id = auth.uid()),
    false
  )
$$;
revoke all on function public.linea_account_is_locked() from public;
grant execute on function public.linea_account_is_locked() to authenticated;

create or replace function public.linea_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select exists (
    select 1 from public.nguoi_dung n
    where n.id = auth.uid() and n.role = 'admin'::public.app_role
  )
$$;
revoke all on function public.linea_is_admin() from public;
grant execute on function public.linea_is_admin() to authenticated;

drop policy if exists "dashboard_read_own_enrollments" on public.ghi_danh;
create policy "dashboard_read_own_enrollments"
on public.ghi_danh for select to authenticated
using (
  ma_nguoi_dung = (select auth.uid())
  and not public.linea_account_is_locked()
);

drop policy if exists "dashboard_read_own_progress" on public.tien_do_bai_hoc;
create policy "dashboard_read_own_progress"
on public.tien_do_bai_hoc for select to authenticated
using (
  ma_nguoi_dung = (select auth.uid())
  and not public.linea_account_is_locked()
);

drop policy if exists "dashboard_read_enrolled_published_courses" on public.khoa_hoc;
create policy "dashboard_read_enrolled_published_courses"
on public.khoa_hoc for select to authenticated
using (
  not public.linea_account_is_locked()
  and (
    public.linea_is_admin()
    or ma_giao_vien = (select auth.uid())
    or (
      trang_thai = 'DA_DANG'
      and exists (
        select 1 from public.ghi_danh g
        where g.ma_khoa_hoc = khoa_hoc.ma_khoa_hoc
          and g.ma_nguoi_dung = (select auth.uid())
          and g.trang_thai in ('DANG_HOC', 'HOAN_THANH')
      )
    )
  )
);

drop policy if exists "dashboard_read_enrolled_chapters" on public.chuong;
create policy "dashboard_read_enrolled_chapters"
on public.chuong for select to authenticated
using (
  not public.linea_account_is_locked()
  and (
    public.linea_is_admin()
    or exists (
      select 1 from public.khoa_hoc k
      join public.ghi_danh g on g.ma_khoa_hoc = k.ma_khoa_hoc
      where k.ma_khoa_hoc = chuong.ma_khoa_hoc
        and k.trang_thai = 'DA_DANG'
        and g.ma_nguoi_dung = (select auth.uid())
        and g.trang_thai in ('DANG_HOC', 'HOAN_THANH')
    )
  )
);

