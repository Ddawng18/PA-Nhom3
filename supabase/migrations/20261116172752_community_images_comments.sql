alter table public.community_posts add column image_url text;

create table public.community_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  author_id uuid not null references public.nguoi_dung(id),
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index community_comments_post_created_idx on public.community_comments(post_id, created_at, id);
create index community_comments_author_idx on public.community_comments(author_id);
alter table public.community_comments enable row level security;
revoke all on public.community_comments from public, anon, authenticated;
revoke all on sequence public.community_comments_id_seq from public, anon, authenticated;

