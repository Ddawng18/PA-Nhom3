-- Community reactions, reports and moderation state.
-- All writes go through the ASP.NET API; browser roles receive no table grants.

alter table public.community_posts
  add column status varchar(16) not null default 'VISIBLE';
alter table public.community_posts
  add constraint community_posts_status_check check (status in ('VISIBLE', 'HIDDEN'));
create index community_posts_status_created_idx
  on public.community_posts (status, created_at desc, id desc);

create table public.community_post_likes (
  post_id bigint not null references public.community_posts(id) on delete cascade,
  user_id uuid not null references public.nguoi_dung(id),
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);
create index community_post_likes_user_idx on public.community_post_likes (user_id, created_at desc);
alter table public.community_post_likes enable row level security;
revoke all on public.community_post_likes from public, anon, authenticated;

create table public.community_post_reports (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  reporter_id uuid not null references public.nguoi_dung(id),
  reason varchar(500) not null check (char_length(btrim(reason)) between 5 and 500),
  status varchar(16) not null default 'OPEN' check (status in ('OPEN', 'RESOLVED', 'DISMISSED')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewer_id uuid references public.nguoi_dung(id),
  note varchar(1000),
  unique (post_id, reporter_id),
  check (status = 'OPEN' or reviewed_at is not null)
);
create index community_post_reports_status_created_idx
  on public.community_post_reports (status, created_at, id);
create index community_post_reports_post_idx on public.community_post_reports (post_id);
alter table public.community_post_reports enable row level security;
revoke all on public.community_post_reports from public, anon, authenticated;

-- A report itself is never public. Resolved reports keep the reviewer note for audit.
alter table public.lich_su_trang_thai
  drop constraint if exists lich_su_trang_thai_loai_doi_tuong_check;
alter table public.lich_su_trang_thai
  add constraint lich_su_trang_thai_loai_doi_tuong_check
  check (loai_doi_tuong in ('NGUOI_DUNG', 'HO_SO_GIAO_VIEN', 'KHOA_HOC', 'BAI_NOP', 'DON_HANG', 'CONG_DONG'));
