-- Public reading and authenticated writing are mediated by the API.
create table public.community_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.nguoi_dung(id),
  title varchar(160) not null check (char_length(btrim(title)) between 1 and 160),
  body text not null check (char_length(btrim(body)) between 1 and 5000),
  created_at timestamptz not null default now()
);
create index community_posts_created_id_idx on public.community_posts (created_at desc, id desc);
alter table public.community_posts enable row level security;
revoke all on public.community_posts from public, anon, authenticated;
